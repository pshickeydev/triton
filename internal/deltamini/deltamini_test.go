package deltamini

import "testing"

// A quote inside a line comment is comment text, not a string literal.
func TestReviewIgnoresQuotesInComments(t *testing.T) {
	code := "-- a \" note\nd1 $ sound \"bd\""
	want := "-- a \" note\nd1 $ sound (deltaContext 11 1 \"bd\")"
	if got := Delta(code, 0); got != want {
		t.Fatalf("Delta rewrote comment text into invalid source:\n%q\nwant:\n%q", got, want)
	}
}

// A quote escaped by an odd backslash run stays inside the literal.
func TestReviewPreservesEscapedQuotes(t *testing.T) {
	code := `d1 $ sound "bd\"sn"`
	want := `d1 $ sound (deltaContext 11 0 "bd\"sn")`
	if got := Delta(code, 0); got != want {
		t.Fatalf("Delta terminated an escaped string early:\n%q\nwant:\n%q", got, want)
	}
}

// Cases were generated by running the reference Haskell deltaMini
// (tidal-core, Sound.Tidal.Pattern) on each input, with the start line
// shifted for the block-offset cases.
func TestDelta(t *testing.T) {
	tests := []struct {
		name      string
		code      string
		startLine int
		want      string
	}{
		{
			name: "single literal",
			code: `d1 $ sound "bd sn"`,
			want: `d1 $ sound (deltaContext 11 0 "bd sn")`,
		},
		{
			name: "two literals on one line",
			code: `d1 $ sound "bd sn" # n "0 1"`,
			want: `d1 $ sound (deltaContext 11 0 "bd sn") # n (deltaContext 23 0 "0 1")`,
		},
		{
			name: "newline inside literal",
			code: "d1 $ sound \"bd\n~ sn\"",
			want: "d1 $ sound (deltaContext 11 0 \"bd\n~ sn\")",
		},
		{
			name: "literals on later lines",
			code: "d1 $\n  sound \"bd\"\n  # n \"0\"",
			want: "d1 $\n  sound (deltaContext 8 1 \"bd\")\n  # n (deltaContext 6 2 \"0\")",
		},
		{
			name: "no literals passes through",
			code: "hush",
			want: "hush",
		},
		{
			name: "unterminated literal mirrors haskell",
			code: `d1 $ sound "bd`,
			want: `d1 $ sound (deltaContext 11 0 "bd`,
		},
		{
			name: "bracketed mininotation",
			code: `d1 $ s "[bd sn] cp"`,
			want: `d1 $ s (deltaContext 7 0 "[bd sn] cp")`,
		},
		{
			name:      "block offset shifts line",
			code:      `d2 $ up "0 1" # sound "arpy"`,
			startLine: 3,
			want:      `d2 $ up (deltaContext 8 3 "0 1") # sound (deltaContext 22 3 "arpy")`,
		},
		{
			name:      "block offset with internal newlines",
			code:      "d1 $\n  sound \"bd\"\n  # n \"0\"",
			startLine: 5,
			want:      "d1 $\n  sound (deltaContext 8 6 \"bd\")\n  # n (deltaContext 6 7 \"0\")",
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			if got := Delta(tt.code, tt.startLine); got != tt.want {
				t.Errorf("Delta(%q, %d):\n got: %q\nwant: %q", tt.code, tt.startLine, got, tt.want)
			}
		})
	}
}

// Quotes inside block comments, nested or not, are comment text.
func TestIgnoresQuotesInBlockComments(t *testing.T) {
	code := "{- outer {- inner \" q -} note \" x -}\nd1 $ sound \"bd\""
	want := "{- outer {- inner \" q -} note \" x -}\nd1 $ sound (deltaContext 11 1 \"bd\")"
	if got := Delta(code, 0); got != want {
		t.Fatalf("Delta rewrote block comment text:\n%q\nwant:\n%q", got, want)
	}
}

// An even backslash run escapes to an escaped backslash, so the quote
// after it closes the literal.
func TestEvenBackslashRunClosesLiteral(t *testing.T) {
	code := `d1 $ sound "bd\\"`
	want := `d1 $ sound (deltaContext 11 0 "bd\\")`
	if got := Delta(code, 0); got != want {
		t.Fatalf("quote after an even backslash run should close the literal:\n%q\nwant:\n%q", got, want)
	}
}

// Dashes followed by a symbol character are an operator, not a comment.
func TestOperatorDashesAreNotComment(t *testing.T) {
	code := "hush -- done"
	want := "hush -- done"
	if got := Delta(code, 0); got != want {
		t.Fatalf("Delta rewrote a trailing comment:\n%q\nwant:\n%q", got, want)
	}
	code = "--> 2"
	want = "--> 2"
	if got := Delta(code, 0); got != want {
		t.Fatalf("Delta rewrote the --> operator as a literal:\n%q\nwant:\n%q", got, want)
	}
}
